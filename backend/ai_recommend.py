def recommend_specialty(symptom_text: str) -> Tuple[str, float, List[str]]:
    """
    აანალიზებს სიმპტომების ტექსტს და აბრუნებს (საუკეთესო_სპეციალობა,
    confidence_score, დამთხვეული_საკვანძო_სიტყვები).

    ქულა გამოითვლება დამთხვეული საკვანძო სიტყვების წონების ჯამით
    (და არა უბრალო რაოდენობით), რაც საშუალებას იძლევა სპეციფიკურმა,
    ცალსახად მიმანიშნებელმა სიმპტომებმა მეტი გავლენა იქონიონ
    საბოლოო რეკომენდაციასა და სანდოობის ქულაზე, ვიდრე ზოგადმა.
    """
    text = symptom_text.lower().strip()
    if not text:
        return "ოჯახის ექიმი", 0.3, []

    scores: Dict[str, float] = {}
    matched_map: Dict[str, List[str]] = {}
    for specialty, keywords in SPECIALTY_KEYWORDS.items():
        total = 0.0
        matched = []
        for kw, weight in keywords:
            if kw in text:
                total += weight
                matched.append(kw)
        if matched:
            scores[specialty] = total
            matched_map[specialty] = matched

    if not scores:
        # ვერაფერი დაემთხვა კონკრეტულ სპეციალობას - ვურჩევთ ოჯახის ექიმს
        return "ოჯახის ექიმი", 0.35, []

    ranked = sorted(scores.items(), key=lambda kv: kv[1], reverse=True)
    specialty_name, top_score = ranked[0]
    matched_keywords = matched_map[specialty_name]

    # confidence: 0.45 საბაზისო + ქულის მიხედვით ზრდადი, მაქსიმუმ 0.97-მდე
    confidence = min(0.45 + 0.16 * top_score, 0.97)

    return specialty_name, round(confidence, 2), matched_keywords


def rank_specialties(symptom_text: str, limit: int = 3) -> List[Tuple[str, float]]:
    """
    აბრუნებს ტოპ N სპეციალობას ქულების მიხედვით (გამოსადეგია ალტერნატივების
    საჩვენებლად, როცა სიმპტომები ერთდროულად რამდენიმე სპეციალობას ეხმაურება).
    """
    text = symptom_text.lower().strip()
    if not text:
        return []
    scores: Dict[str, float] = {}
    for specialty, keywords in SPECIALTY_KEYWORDS.items():
        total = sum(weight for kw, weight in keywords if kw in text)
        if total > 0:
            scores[specialty] = total
    ranked = sorted(scores.items(), key=lambda kv: kv[1], reverse=True)
    return ranked[:limit]


