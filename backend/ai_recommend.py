def assess_urgency(symptom_text: str) -> Tuple[str, str]:
    """
    აბრუნებს (urgency_level, advice) წყვილს.
    urgency_level ∈ {"emergency", "urgent", "routine"}
    """
    text = symptom_text.lower().strip()
    if not text:
        return "routine", "დაგეგმეთ ვიზიტი თქვენთვის მოსახერხებელ დროს."

    for kw in EMERGENCY_KEYWORDS:
        if kw in text:
            return (
                "emergency",
                "აღწერილი სიმპტომები შესაძლოა გადაუდებელ მდგომარეობას მიემართებოდეს — "
                "გირჩევთ დაუყოვნებლივ დაუკავშირდეთ სასწრაფო დახმარებას (112) ან "
                "მიმართოთ უახლოეს კლინიკის გადაუდებელი დახმარების განყოფილებას.",
            )

    for kw in URGENT_KEYWORDS:
        if kw in text:
            return (
                "urgent",
                "სასურველია ექიმთან ვიზიტი დაგეგმოთ უახლოეს 24 საათში, ნუ გადადებთ ხანგრძლივად.",
            )

    return "routine", "შეგიძლიათ ვიზიტი დაგეგმოთ ჩვეულებრივი გრაფიკით."


