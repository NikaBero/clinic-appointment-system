POSITIVE_WORDS = [
    "კარგი", "საუკეთესო", "მადლობა", "პროფესიონალი", "თავაზიანი", "სასიამოვნო",
    "კმაყოფილი", "დამეხმარა", "შესანიშნავი", "great", "good", "excellent", "thanks",
]
NEGATIVE_WORDS = [
    "ცუდი", "უხეში", "დაგვიანდა", "არაპროფესიონალი", "უკმაყოფილო", "ცუდად",
    "bad", "terrible", "rude", "late", "disappointed",
]


def classify_review_sentiment(rating: int, comment: str | None) -> str:
    """
    აბრუნებს "positive" / "neutral" / "negative" შეფასების ვარსკვლავებისა და
    კომენტარის ტექსტში საკვანძო სიტყვების კომბინაციით.
    """
    text = (comment or "").lower()
    score = 0
    if rating >= 4:
        score += 1
    elif rating <= 2:
        score -= 1

    if any(w in text for w in POSITIVE_WORDS):
        score += 1
    if any(w in text for w in NEGATIVE_WORDS):
        score -= 1

    if score > 0:
        return "positive"
    if score < 0:
        return "negative"
    return "neutral"
